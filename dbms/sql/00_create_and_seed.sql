-- ============================================================
--  学生管理システム データベース作成スクリプト
--  対象DBMS: SQLite
--  これを一番最初に実行して、演習用データベースを作ります。
--
--  テーブル同士の関係（ER図）
--    teachers ─1対多─> subjects   （1人の教員が複数の科目を担当する）
--    teachers ─1対多─> classes    （担任。ただし同じ入学年度では1人1クラスまで）
--    classes  ─1対多─> students
--    students ─1対多─> scores <─多対1─ subjects
--      ※ scores は「学生 × 科目」の多対多をつなぐ中間テーブル
-- ============================================================

-- SQLiteは既定で外部キー制約チェックが無効になっているため、有効化する
PRAGMA foreign_keys = ON;

-- 既存のテーブルがあれば一度削除する（作り直したいときに使う）
-- 外部キーで参照している側（子）から先に削除する
DROP TABLE IF EXISTS scores;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS subjects;
DROP TABLE IF EXISTS classes;
DROP TABLE IF EXISTS teachers;
DROP TABLE IF EXISTS non_normalized_demo;
DROP TABLE IF EXISTS flat_school_records;

-- ----------------------------------------------------------
-- 教員テーブル
-- ----------------------------------------------------------
CREATE TABLE teachers (
    teacher_id   INTEGER PRIMARY KEY,   -- 主キー：教員を一意に識別するID
    teacher_name TEXT NOT NULL,         -- 敬称の「先生」はデータに含めない
    kana         TEXT NOT NULL,
    hire_date    TEXT NOT NULL          -- 採用日 'YYYY-MM-DD' 形式の文字列
);

-- ----------------------------------------------------------
-- クラステーブル（「入学年度 × 学科」で1クラス）
-- ----------------------------------------------------------
CREATE TABLE classes (
    class_id        INTEGER PRIMARY KEY,    -- 主キー
    enrollment_year INTEGER NOT NULL
                    CHECK (enrollment_year BETWEEN 2000 AND 2100),  -- 入学年度 例: 2026
    department_name TEXT NOT NULL,          -- 学科名 例: 'ITエンジニア学科'
    teacher_id      INTEGER NOT NULL,       -- 外部キー：担任の教員（teachersを参照）
    FOREIGN KEY (teacher_id) REFERENCES teachers(teacher_id),
    UNIQUE (enrollment_year, department_name),  -- 同じ入学年度に同じ学科のクラスは1つだけ
    UNIQUE (enrollment_year, teacher_id)        -- 同じ入学年度に1人の教員が担任できるのは1クラスだけ
);

-- ----------------------------------------------------------
-- 学生テーブル
-- ----------------------------------------------------------
CREATE TABLE students (
    student_id   INTEGER PRIMARY KEY,   -- 主キー：学籍番号（6桁 例: 261001）
    student_name TEXT NOT NULL,
    kana         TEXT,
    birth_date   TEXT NOT NULL,         -- 'YYYY-MM-DD' 形式の文字列
    class_id     INTEGER NOT NULL,      -- 外部キー：classesテーブルのclass_idを参照
    FOREIGN KEY (class_id) REFERENCES classes(class_id)
);

-- ----------------------------------------------------------
-- 科目テーブル
-- ----------------------------------------------------------
CREATE TABLE subjects (
    subject_id   INTEGER PRIMARY KEY,   -- 主キー
    subject_name TEXT NOT NULL UNIQUE,  -- 同じ名前の科目は登録できない
    credit       INTEGER NOT NULL CHECK (credit > 0),  -- 単位数
    teacher_id   INTEGER NOT NULL,      -- 外部キー：担当の教員（teachersを参照）
    FOREIGN KEY (teacher_id) REFERENCES teachers(teacher_id)
);

-- ----------------------------------------------------------
-- 成績テーブル（「学生 × 科目」の実績データ）
-- ----------------------------------------------------------
CREATE TABLE scores (
    score_id     INTEGER PRIMARY KEY,   -- 主キー
    student_id   INTEGER NOT NULL,      -- 外部キー：studentsテーブルを参照
    subject_id   INTEGER NOT NULL,      -- 外部キー：subjectsテーブルを参照
    score        INTEGER NOT NULL CHECK (score BETWEEN 0 AND 100),  -- 0〜100点
    exam_date    TEXT NOT NULL,         -- 'YYYY-MM-DD' 形式の文字列
    FOREIGN KEY (student_id) REFERENCES students(student_id),
    FOREIGN KEY (subject_id) REFERENCES subjects(subject_id),
    UNIQUE (student_id, subject_id, exam_date)  -- 同じ試験の成績を二重に登録させない
);

